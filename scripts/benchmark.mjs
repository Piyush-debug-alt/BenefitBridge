import { availableParallelism, cpus, release, totalmem } from 'node:os';
import { resolve } from 'node:path';
import { performance } from 'node:perf_hooks';
import { MongoMemoryServer } from 'mongodb-memory-server-core';
import { readConfig } from '../api/src/config/env.js';
import { connectDatabase } from '../api/src/config/database.js';
import { searchSchemes } from '../api/src/modules/catalogue/routes.js';
import { enqueueSync, workSource } from '../api/src/modules/ingestion/sync.js';
import { processNotificationBatch } from '../api/src/modules/notifications/worker.js';

const volume = Number(process.argv[2] ?? 1000);
if (!Number.isSafeInteger(volume) || volume < 1 || volume > 100_000) throw new Error('Supply a record count from 1 to 100000.');
const metadata = {
  id: 'scale-fixtures', name: 'Fictional scale test', baseUrl: 'https://scale.example.invalid',
  accessPermissions: 'Fictional benchmark records generated by BenefitBridge', retentionPolicy: 'reference_only',
  evidenceOrigins: ['https://scale.example.invalid'],
};
const regions = ['MH', 'KA', 'TN', 'KL', 'GJ'];
const categories = ['Education', 'Agriculture', 'Health', 'Transport', 'Housing', 'Industry', 'Research'];
const synthetic = 'synthetic';

function fixture(index, changed) {
  const externalRecordId = 'load-' + index;
  const nationwide = index % 11 === 0;
  const sector = categories[index % categories.length];
  return {
    updatedAt: changed ? '2026-10-02T00:00:00Z' : '2026-10-01T00:00:00Z',
    record: {
      externalRecordId, canonicalName: 'Fictional ' + sector + ' Scheme ' + index % 1000,
      description: 'Synthetic ' + sector + ' support. ' + (index % 131 === 0 ? 'Solar installation.' : 'Community resources.'),
      categoryIds: [sector], governmentLevel: nationwide ? 'central' : 'state', issuer: 'Fictional issuer ' + index % 37,
      nationwide, stateCodes: nationwide ? [] : [regions[index % regions.length]], lifecycleStatus: 'active',
      verificationStatus: 'verified', sourceRefs: [{ label: 'Fictional source', url: metadata.baseUrl + '/' + externalRecordId }],
      benefits: changed ? ['Fictional updated materials'] : index % 5 === 0 ? [] : ['Fictional materials'],
      lastVerifiedAt: '2026-10-01T00:00:00Z',
    },
  };
}
const adapter = { metadata, incremental: true, async page({ mode, cursor, checkpoint }) {
  const start = Number(cursor ?? 0);
  if (mode === 'snapshot' && start > 0 && start % 5000 === 0) console.error('Snapshot staged and published ' + start + ' records.');
  const end = Math.min(mode === 'incremental' ? Math.min(50, volume) : volume, start + 500);
  return {
    records: mode === 'incremental' && checkpoint === 'delta-1' ? [] : Array.from(
      { length: end - start }, (_, offset) => fixture(start + offset, mode === 'incremental'),
    ),
    nextCursor: mode === 'snapshot' && end < volume ? String(end) : null,
    ...(mode === 'snapshot' ? { snapshotKey: 'scale-v1-' + volume, complete: end === volume, checkpoint: 'base' }
      : { checkpoint: 'delta-1' }),
  };
} };

function round(value) { return Math.round(value * 100) / 100; }
function quantile(samples, p) { return round(samples[Math.ceil(samples.length * p) - 1] ?? 0); }
function describePlan(explain) {
  const stages = [];
  function walk(value) {
    if (!value || typeof value !== 'object') return;
    if (value.stage) stages.push(value.indexName ? value.stage + '(' + value.indexName + ')' : value.stage);
    Object.values(value).forEach(walk);
  }
  walk(explain.queryPlanner.winningPlan);
  return { stages: [...new Set(stages)], keysExamined: explain.executionStats.totalKeysExamined,
    docsExamined: explain.executionStats.totalDocsExamined, returned: explain.executionStats.nReturned };
}

const mongod = await MongoMemoryServer.create({ binary: { downloadDir: resolve('.local/mongodb') } });
let connection;
try {
  const config = readConfig({ LOADTEST_MONGODB_URI: mongod.getUri() }, { loadtest: true });
  const database = await connectDatabase(config);
  connection = database.connection;
  const { models } = database;
  const publish = { autoPublish: true };
  async function sync(mode) {
    const start = performance.now();
    const job = await enqueueSync(models, synthetic, metadata.id, mode);
    const result = await workSource(models, synthetic, adapter, publish);
    if (result.status !== 'succeeded') throw new Error('Benchmark sync failed: ' + (await models.SyncJob.findById(job.id)).errorCode);
    const elapsedMs = performance.now() - start;
    const stats = (await models.SyncJob.findById(job.id)).stats;
    return { elapsedMs: round(elapsedMs), recordsPerSecond: round(stats.records / (elapsedMs / 1000)), stats };
  }
  const initial = await sync('snapshot');

  const filters = [{ q: 'solar' }, { state: 'MH' }, { category: 'Education', state: 'MH' }];
  const published = { dataset: synthetic, publicationStatus: 'published' };
  const plans = [];
  for (const filter of filters) {
    const [find] = searchSchemes(models.Scheme, published, { ...filter, page: 1, limit: 10 });
    plans.push({ filter, ...describePlan(await find.explain('executionStats')) });
  }

  const searches = [];
  let incremental;
  for (const concurrency of [1, 10, 50]) {
    const samples = [];
    let syncFinished;
    let searchFinished = false;
    const background = concurrency === 10 ? Promise.all([
      sync('incremental').then(result => { incremental = result; syncFinished = !searchFinished; }),
      processNotificationBatch(models, synthetic, { limit: 20 }),
    ]) : null;
    const start = performance.now();
    let failed = 0;
    await Promise.all(Array.from({ length: concurrency }, async (_, worker) => {
      for (let request = worker; request < 150; request += concurrency) {
        const begin = performance.now();
        try {
          await Promise.all(searchSchemes(models.Scheme, published, { ...filters[request % 3], page: 1, limit: 10 }));
          samples.push(performance.now() - begin);
        } catch {
          failed++;
        }
      }
    }));
    searchFinished = true;
    const elapsedMs = performance.now() - start;
    const workers = background && await background;
    samples.sort((a, b) => a - b);
    searches.push({ concurrency, requests: 150, failed, elapsedMs: round(elapsedMs),
      requestsPerSecond: round(150 / (elapsedMs / 1000)), p50Ms: quantile(samples, 0.5),
      p95Ms: quantile(samples, 0.95), p99Ms: quantile(samples, 0.99),
      ...(workers && { incrementalFinishedDuringSearch: syncFinished, notificationWorker: workers[1] }),
    });
  }

  await connection.db.admin().command({ fsync: 1 });
  const stats = await connection.db.stats();
  const server = await connection.db.admin().serverInfo();
  const publishedCount = await models.Scheme.countDocuments(published);
  if (publishedCount !== volume) throw new Error('Unexpected published record count: ' + publishedCount);
  console.log(JSON.stringify({
    volume, publishedCount, node: process.version, os: release(), cpu: cpus()[0]?.model,
    logicalProcessors: availableParallelism(), ramGiB: round(totalmem() / 2 ** 30),
    mongodb: server.version, storage: 'temporary standalone MongoDB', searchPath: 'catalogue Mongoose list + count, warmed by explain plans',
    initial, incremental, searches, plans,
    mongoBytes: { data: stats.dataSize, storage: stats.storageSize, indexes: stats.indexSize },
  }, null, 2));
} finally {
  await connection?.close();
  await mongod.stop();
}
